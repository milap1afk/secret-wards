#!/usr/bin/env python3
"""Train the small name scorer used by wards/namemodel.py ("is this token an Indian personal name?").

  python3 tools/train_name_model.py [--dev kit/dev]  -> wards/data/name_model.json + held-out metrics

Model: multinomial naive Bayes over character 2-4-grams with word-boundary markers, Latin and Devanagari.
Standard library only; deterministic (fixed seed). No pretrained component of any kind.

Training data (generated here, nothing downloaded):
  positives  given names and surnames from wards/gazetteer.py, plus spelling variants generated by rules
             (ee/i, oo/u, aa/a, w/v, sh/s, ph/f, doubled letters, final -a/-aa) and Devanagari forms written
             by a rule-based Latin->Devanagari transliterator (tools/chaos.py);
  negatives  drug names, medical terms, Hinglish and English words: the gazetteer's clinical vocabulary, the
             tokens of the practice corpus' medical "preserve" values and clean documents (no PII there).
20 % of the positive NAMES (all variants of a held-out name stay together) and 20 % of negatives are held out.
"""
import argparse
import json
import math
import random
import re
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tools"))
from wards import gazetteer as gz  # noqa: E402
from chaos import latin_to_deva  # noqa: E402

NMIN, NMAX = 2, 4


def grams(tok: str):
    t = "^" + tok.lower() + "$"
    for n in range(NMIN, NMAX + 1):
        for i in range(len(t) - n + 1):
            yield t[i:i + n]


def variants(name: str):
    out = {name}
    rules = [("ee", "i"), ("i", "ee"), ("oo", "u"), ("u", "oo"), ("aa", "a"), ("w", "v"), ("v", "w"), ("sh", "s"),
             ("ph", "f"), ("kh", "k")]
    for a, b in rules:
        if a in name:
            out.add(name.replace(a, b, 1))
    if name.endswith("a"):
        out.add(name + "a")
        out.add(name[:-1])
    out.add(re.sub(r"(.)\1", r"\1", name))
    return {v for v in out if len(v) >= 3}


def corpus_negatives(dev: Path):
    words = set()
    truth = json.loads((dev / "truth" / "truth.json").read_text(encoding="utf-8"))
    for f in truth["files"].values():
        for u in f["units"].values():
            for p in u.get("preserve", []):
                if p.get("kind") in ("doctor", "context"):
                    continue          # doctor names are names; skip them as negatives
                words |= set(re.findall(r"[A-Za-z]{3,}|[ऀ-ॿ]{2,}", p["text"]))
    for p in (dev / "input" / "clean").glob("*"):
        try:
            words |= set(re.findall(r"[A-Za-z]{3,}|[ऀ-ॿ]{2,}", p.read_text(encoding="utf-8")))
        except UnicodeDecodeError:
            pass
    return {w.lower() for w in words}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dev", default="kit/dev")
    ap.add_argument("--out", default=str(ROOT / "wards" / "data" / "name_model.json"))
    a = ap.parse_args()
    rng = random.Random(20261127)
    names = sorted(gz.GIVEN_NAMES | gz.SURNAMES)
    rng.shuffle(names)
    cut = int(len(names) * 0.8)
    train_names, test_names = names[:cut], names[cut:]
    neg = sorted((gz.NON_NAME_WORDS | corpus_negatives(Path(a.dev))) - set(names) - gz.HONORIFIC_SUFFIX)
    neg = [w for w in neg if len(w) >= 3]
    rng.shuffle(neg)
    ncut = int(len(neg) * 0.8)
    train_neg, test_neg = neg[:ncut], neg[ncut:]

    def expand(ns):
        out = []
        for n in ns:
            for v in variants(n):
                out.append(v)
                out.append(latin_to_deva(v))
        return out
    pos_tr, pos_te = expand(train_names), expand(test_names)
    counts = {1: Counter(), 0: Counter()}
    for tok in pos_tr:
        counts[1].update(grams(tok))
    for tok in train_neg:
        counts[0].update(grams(tok))
    vocab = set(counts[1]) | set(counts[0])
    tot = {c: sum(counts[c].values()) for c in (0, 1)}
    V = len(vocab)
    alpha = 0.5
    # store log-likelihood ratios per gram (pruned) and the default for unseen grams
    llr = {}
    for g in vocab:
        p1 = (counts[1][g] + alpha) / (tot[1] + alpha * V)
        p0 = (counts[0][g] + alpha) / (tot[0] + alpha * V)
        r = math.log(p1 / p0)
        if counts[1][g] + counts[0][g] >= 2 and abs(r) > 0.05:
            llr[g] = round(r, 3)
    unseen = round(math.log(((alpha) / (tot[1] + alpha * V)) / ((alpha) / (tot[0] + alpha * V))), 3)
    prior = round(math.log(len(pos_tr) / len(train_neg)), 3)

    def score(tok):
        gs = list(grams(tok))
        return prior + sum(llr.get(g, unseen) for g in gs) / max(len(gs), 1) * 4

    # pick the threshold on TRAINING data for high precision (names must rarely be confused with medicine)
    cands = sorted(set(round(x * 0.25, 2) for x in range(-8, 24)))
    best = None
    for th in cands:
        tp = sum(1 for t in pos_tr if score(t) > th)
        fp = sum(1 for t in train_neg if score(t) > th)
        prec = tp / max(tp + fp, 1)
        if prec >= 0.97:
            best = th
            break
    th = best if best is not None else 2.0

    def metrics(pos, negs):
        tp = sum(1 for t in pos if score(t) > th)
        fp = sum(1 for t in negs if score(t) > th)
        return tp / max(len(pos), 1), tp / max(tp + fp, 1)
    rec_tr, prec_tr = metrics(pos_tr, train_neg)
    rec_te, prec_te = metrics(pos_te, test_neg)
    model = {"kind": "char-ngram multinomial naive Bayes (log-likelihood ratios)", "n": [NMIN, NMAX],
             "prior": prior, "unseen": unseen, "threshold": th, "llr": dict(sorted(llr.items())),
             "trained_on": {"positive_tokens": len(pos_tr), "negative_tokens": len(train_neg)},
             "held_out": {"names": len(test_names), "positive_tokens": len(pos_te), "negative_tokens": len(test_neg),
                          "recall": round(rec_te, 3), "precision": round(prec_te, 3)}}
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out).write_text(json.dumps(model, ensure_ascii=False, separators=(",", ":")) + "\n", encoding="utf-8")
    print(f"grams kept {len(llr)}, threshold {th}")
    print(f"train  recall {rec_tr:.3f} precision {prec_tr:.3f}")
    print(f"held-out ({len(test_names)} unseen names, {len(test_neg)} unseen non-names): recall {rec_te:.3f} precision {prec_te:.3f}")
    print(f"model size {Path(a.out).stat().st_size // 1024} KB -> {a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
